/* ==========================================================================
   交互小说引擎 · names.js
   生成小镇名字、人物名字。所有名字都有"含义"——
   人物的名字要能成为一句对话的引子。
   ========================================================================== */

const Names = (() => {
  'use strict';

  /* ------------------------------------------------------------------
     镇名：前缀（雾/青/白/…）+ 中缀（渡/溪/桥/…）+ 镇
     前缀决定镇子的气质，会写进开场白
     ------------------------------------------------------------------ */

  const TOWN_PREFIX = [
    ['雾', '常年有雾，清晨的河面上什么也看不清'],
    ['青', '四面是山，山色一年到头是青的'],
    ['白', '产盐，风吹过来有咸味'],
    ['松', '满山松林，夜里能听见松涛'],
    ['石', '石头多，镇上的路都是石板铺的'],
    ['枫', '秋天满镇红叶'],
    ['沙', '靠江，江滩上是细沙'],
    ['柳', '沿河种满柳树'],
    ['云', '地势高，云常从镇子中间穿过'],
    ['雨', '一年里大半时间在下雨'],
    ['茶', '山上有茶园，镇里飘着茶香'],
    ['灯', '古时是航道上的灯站'],
  ];
  const TOWN_MIDDLE = ['渡', '溪', '桥', '岭', '港', '集', '湾', '坡', '口', '巷', '浦', '埠'];

  function townName(rng) {
    const p = RNG.pick(rng, TOWN_PREFIX);
    const m = RNG.pick(rng, TOWN_MIDDLE);
    return { name: p[0] + m[0] + '镇', flavor: p[1], prefix: p[0], middle: m[0] };
  }

  /* ------------------------------------------------------------------
     人名
     ------------------------------------------------------------------ */

  const SURNAMES = ['陈', '林', '周', '吴', '郑', '许', '沈', '顾', '苏', '方',
                    '宋', '陆', '何', '余', '傅', '韩', '姜', '程', '邵', '江'];

  /** 名 + 含义。含义写进人物卡，也是对话话题的引子 */
  const GIVEN = [
    ['望秋', '盼着收成'],
    ['守溪', '守着家门前的溪水'],
    ['怀远', '心在远方'],
    ['念慈', '念着长辈的慈爱'],
    ['长庚', '黄昏时最亮的那颗星'],
    ['月生', '月亮升起来时出生'],
    ['雨眠', '出生那夜雨下个不停'],
    ['砚青', '家里出过读书人'],
    ['见山', '睁开眼先看见山'],
    ['小满', '节气里出生'],
    ['渡云', '渡口上漂来的孩子'],
    ['灯夜', '灯站最亮的那晚'],
    ['拾薪', '捡柴火的意思'],
    ['晚棠', '海棠开得晚'],
    ['复归', '走了又回来'],
    ['石青', '石头缝里的青色'],
    ['江临', '住在江边'],
    ['秋声', '秋天出生'],
    ['客舟', '客船经过时出生'],
    ['未眠', '夜里不睡的人'],
    ['岁寒', '腊月出生'],
    ['照庭', '光能照进院子'],
    ['听钟', '听着钟声长大'],
    ['既白', '天快亮的时候'],
  ];

  const USED = new Set();

  /** 生成一个名字，同一局内不重复 */
  function personName(rng) {
    for (let tries = 0; tries < 200; tries++) {
      const s = RNG.pick(rng, SURNAMES);
      const g = RNG.pick(rng, GIVEN);
      const full = s + g[0];
      if (USED.has(full)) continue;
      USED.add(full);
      return { name: full, surname: s, given: g[0], meaning: g[1] };
    }
    // 极端情况下退化为编号
    const fallback = '路人' + USED.size;
    USED.add(fallback);
    return { name: fallback, surname: '路', given: '人' + USED.size, meaning: '路过的人' };
  }

  /** 重新开始（每局开局时清空已用名字） */
  function reset() { USED.clear(); }

  return { townName, personName, reset };
})();

window.Names = Names;
